/*
This script analyzes the magnitude and distribution of key business metrics
across different dimensions such as country, gender, and product category.

Specifically, it:
- Measures how customers are distributed geographically and demographically
- Evaluates product distribution across categories
- Analyzes average product cost by category
- Calculates total revenue by category and customer
- Examines sales volume across regions

Additionally this highlights which segments contribute the most to the business
*/

--Total number of customers by country

SELECT
	country,
	COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
order by COUNT(customer_key) DESC

--Total number of customers by gender

SELECT
	gender,
	COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY gender
order by COUNT(customer_key) DESC

--Total number of customers by category

SELECT
	category,
	COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY category
order by COUNT(product_key) DESC

--Average product cost in each category

SELECT
	category,
	AVG(product_cost) AS avg_product_cost
FROM gold.dim_products
GROUP BY category
order by AVG(product_cost) DESC

--Total revenue for each category

SELECT
	p.category,
	SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key=f.product_key
GROUP BY p.category
ORDER BY SUM(f.sales_amount) DESC

--Total revenue generated by each customer

SELECT 
c.customer_key,
c.first_name,
c.last_name,
SUM(f.sls_price) as total_sales
FROM 
gold.fact_sales f LEFT JOIN 
gold.dim_customers c ON c.customer_id=f.customer_id
GROUP BY 
c.customer_key,
c.first_name,
c.last_name
ORDER BY SUM(f.sls_price) DESC

--Total distribution of sold items for each country

SELECT 
c.country,
SUM(f.quantity) as sold_items_amount
FROM 
gold.fact_sales f LEFT JOIN 
gold.dim_customers c ON c.customer_id=f.customer_id
GROUP BY 
c.country
ORDER BY SUM(f.quantity) DESC

--Average revenue per customer by country

SELECT 
    c.country,
    SUM(f.sales_amount) * 1.0 / COUNT(DISTINCT c.customer_id) AS avg_revenue_per_customer
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c 
    ON c.customer_id = f.customer_id
GROUP BY c.country
ORDER BY avg_revenue_per_customer DESC

